"""Writes lean/DetPrimality/Barrier/dual_Data.lean and dual_Run<k>.lean (called from dual_gen.py)."""
import os, glob

def plist(pairs, per=4, ind="  "):
    items = ["(%d, %d)" % p for p in pairs]
    lines = [", ".join(items[i:i+per]) for i in range(0, len(items), per)]
    return "[" + (",\n" + ind).join(lines) + "]"

def emit(outdir, V, D, A, ck, R, chunks, c):
    used = sorted({j for prog, _ in chunks for j, _ in prog})
    idx = {j: i for i, j in enumerate(used)}
    ncell = sum(n for prog, _ in chunks for _, n in prog)
    Yf = chunks[-1][1][2]
    o = []
    o.append("import DetPrimality.Barrier.dual_Cert\n")
    o.append("/-!\n# Data of the dual certificate (generated by `research/barrier/dual_gen.py`; do not edit)\n")
    o.append("`dualVD`: nodes `(V, D)`, i.e. the dual function `ψ(t) = s(2πt) e^{πt}` where the step function")
    o.append("`s` has jump `-D/dDd` at `v = V/dDv` (see `dual_Coeff.lean`).  `dualVA`: `(V, α)` with")
    o.append("`α/dSa ≈ (D/dDd) e^{v/2}`.  `dualLv`: cell radii `r = Rn/dQ` and the rotations `≈ dS · e^{i r v}`.")
    o.append("`dualProg k`, `dualSt k`: the `k`-th piece of the run and the state after it; %d cells in" % ncell)
    o.append("total, covering `[0, %d/65536]` (`≈ %.4f`).\n-/\n" % (Yf, Yf/65536))
    o.append("namespace DetPrimality.Barrier\n")
    o.append("def dualVD : List (ℤ × ℤ) :=\n  " + plist(list(zip(V, D))) + "\n")
    o.append("def dualVA : List (ℤ × ℤ) :=\n  " + plist(list(zip(V, A)), 3) + "\n")
    o.append("def dualPar : DualParZ :=\n  ⟨%d,\n   %d,\n   %d,\n   %d⟩\n" % (ck.Bn, ck.B1n, ck.M2n, c["CN"]))
    lv = []
    for j in used:
        lv.append("(%d,\n   %s)" % (2**(16-j), plist(R[j], 2, "    ")))
    o.append("def dualLv : List (ℤ × List (ℤ × ℤ)) :=\n  [" + ",\n   ".join(lv) + "]\n")
    o.append("def dualYf : ℤ := %d\n" % Yf)
    for k, (prog, (st, err, Y)) in enumerate(chunks):
        o.append("def dualProg%d : List (ℕ × ℕ) :=\n  %s\n" % (k, plist([(idx[j], n) for j, n in prog], 8)))
        o.append("def dualSt%d : DualSt :=\n  ⟨%s,\n   %d, %d⟩\n" % (k, plist(st, 2, "    "), err, Y))
    o.append("theorem dualData_par : dualParChk dualPar dualVA = true := by decide +kernel\n")
    o.append("theorem dualData_rots : dualLvOK dualVA dualLv = true := by decide +kernel\n")
    o.append("theorem dualData_tail : dualTailOK dualPar dualYf = true := by decide +kernel\n")
    o.append("end DetPrimality.Barrier")
    open(os.path.join(outdir, "dual_Data.lean"), "w").write("\n".join(o) + "\n")
    for f in glob.glob(os.path.join(outdir, "dual_Run*.lean")): os.remove(f)
    nf = c["NFILES"]; per = -(-len(chunks)//nf)
    for f in range(nf):
        ks = list(range(f*per, min(len(chunks), (f+1)*per)))
        if not ks: continue
        o = ["import DetPrimality.Barrier.dual_Data\n",
             "/-! Kernel runs of the dual certificate, pieces %d–%d (generated by `research/barrier/dual_gen.py`). -/\n" % (ks[0], ks[-1]),
             "namespace DetPrimality.Barrier\n"]
        for k in ks:
            prev = "(dualInit dualVA)" if k == 0 else "dualSt%d" % (k-1)
            o.append("theorem dualData_run%d :\n    dualRun dualPar dualVA dualLv dualProg%d %s = some dualSt%d := by\n  decide +kernel\n" % (k, k, prev, k))
        o.append("end DetPrimality.Barrier")
        open(os.path.join(outdir, "dual_Run%d.lean" % f), "w").write("\n".join(o) + "\n")
    # the assembling file
    o = ["import DetPrimality.Barrier.dual_Data"] + ["import DetPrimality.Barrier.dual_Run%d" % f for f in range(nf) if f*per < len(chunks)]
    o.append("\n/-! The run of the dual certificate, assembled (generated by `research/barrier/dual_gen.py`). -/\n")
    o.append("namespace DetPrimality.Barrier\n")
    o.append("def dualChain : List (List (ℕ × ℕ) × DualSt) :=\n  [" + ",\n   ".join("(dualProg%d, dualSt%d)" % (k, k) for k in range(len(chunks))) + "]\n")
    o.append("theorem dualData_chain : DualChainOK dualPar dualVA dualLv (dualInit dualVA) dualChain :=")
    o.append("  " + " ".join("(And.intro dualData_run%d" % k for k in range(len(chunks))) + " True.intro" + ")"*len(chunks) + "\n")
    o.append("theorem dualData_end : (dualChainEnd (dualInit dualVA) dualChain).Y = dualYf := by decide +kernel\n")
    o.append("end DetPrimality.Barrier")
    open(os.path.join(outdir, "dual_RunAll.lean"), "w").write("\n".join(o) + "\n")
