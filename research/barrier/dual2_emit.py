"""Writes lean/DetPrimality/Barrier/dual2_Data.lean, dual2_Run<k>.lean, dual2_RunAll.lean (called from dual2_gen.py).
Same as dual_emit.py with the names prefixed `dual2`; the checker itself (dual_Cert.lean) is reused."""
import os, glob

def plist(pairs, per=4, ind="  "):
    items = ["(%d, %d)" % p for p in pairs]
    lines = [", ".join(items[i:i+per]) for i in range(0, len(items), per)]
    return "[" + (",\n" + ind).join(lines) + "]"

def emit(outdir, V, D, A, ck, R, chunks, c):
    used = sorted({j for prog, _ in chunks for j, _ in prog})
    idx = {j: i for i, j in enumerate(used)}
    ncell = sum(n for prog, _ in chunks for _, n in prog)
    Yf = chunks[-1][1][2]
    o = []
    o.append("import DetPrimality.Barrier.dual_Cert\n")
    o.append("/-!\n# Data of the dual certificate (generated by `research/barrier/dual2_gen.py`; do not edit)\n")
    o.append("`dual2VD`: nodes `(V, D)`, i.e. the dual function `ψ(t) = s(2πt) e^{πt}` where the step function")
    o.append("`s` has jump `-D/dDd` at `v = V/dDv` (see `dual_Coeff.lean`).  `dual2VA`: `(V, α)` with")
    o.append("`α/dSa ≈ (D/dDd) e^{v/2}`.  `dual2Lv`: cell radii `r = Rn/dQ` and the rotations `≈ dS · e^{i r v}`.")
    o.append("`dual2Prog k`, `dualSt k`: the `k`-th piece of the run and the state after it; %d cells in" % ncell)
    o.append("total, covering `[0, %d/65536]` (`≈ %.4f`).\n-/\n" % (Yf, Yf/65536))
    o.append("namespace DetPrimality.Barrier\n")
    o.append("def dual2VD : List (ℤ × ℤ) :=\n  " + plist(list(zip(V, D))) + "\n")
    o.append("def dual2VA : List (ℤ × ℤ) :=\n  " + plist(list(zip(V, A)), 3) + "\n")
    o.append("def dual2Par : DualParZ :=\n  ⟨%d,\n   %d,\n   %d,\n   %d⟩\n" % (ck.Bn, ck.B1n, ck.M2n, c["CN"]))
    lv = []
    for j in used:
        lv.append("(%d,\n   %s)" % (2**(16-j), plist(R[j], 2, "    ")))
    o.append("def dual2Lv : List (ℤ × List (ℤ × ℤ)) :=\n  [" + ",\n   ".join(lv) + "]\n")
    o.append("def dual2Yf : ℤ := %d\n" % Yf)
    for k, (prog, (st, err, Y)) in enumerate(chunks):
        o.append("def dual2Prog%d : List (ℕ × ℕ) :=\n  %s\n" % (k, plist([(idx[j], n) for j, n in prog], 8)))
        o.append("def dual2St%d : DualSt :=\n  ⟨%s,\n   %d, %d⟩\n" % (k, plist(st, 2, "    "), err, Y))
    o.append("theorem dual2Data_par : dualParChk dual2Par dual2VA = true := by decide +kernel\n")
    o.append("theorem dual2Data_rots : dualLvOK dual2VA dual2Lv = true := by decide +kernel\n")
    o.append("theorem dual2Data_tail : dualTailOK dual2Par dual2Yf = true := by decide +kernel\n")
    o.append("end DetPrimality.Barrier")
    open(os.path.join(outdir, "dual2_Data.lean"), "w").write("\n".join(o) + "\n")
    for f in glob.glob(os.path.join(outdir, "dual2_Run*.lean")): os.remove(f)
    nf = c["NFILES"]; per = -(-len(chunks)//nf)
    for f in range(nf):
        ks = list(range(f*per, min(len(chunks), (f+1)*per)))
        if not ks: continue
        o = ["import DetPrimality.Barrier.dual2_Data\n",
             "/-! Kernel runs of the dual certificate, pieces %d–%d (generated by `research/barrier/dual2_gen.py`). -/\n" % (ks[0], ks[-1]),
             "namespace DetPrimality.Barrier\n"]
        for k in ks:
            prev = "(dualInit dual2VA)" if k == 0 else "dual2St%d" % (k-1)
            o.append("theorem dual2Data_run%d :\n    dualRun dual2Par dual2VA dual2Lv dual2Prog%d %s = some dual2St%d := by\n  decide +kernel\n" % (k, k, prev, k))
        o.append("end DetPrimality.Barrier")
        open(os.path.join(outdir, "dual2_Run%d.lean" % f), "w").write("\n".join(o) + "\n")
    # the assembling file
    o = ["import DetPrimality.Barrier.dual2_Data"] + ["import DetPrimality.Barrier.dual2_Run%d" % f for f in range(nf) if f*per < len(chunks)]
    o.append("\n/-! The run of the dual certificate, assembled (generated by `research/barrier/dual2_gen.py`). -/\n")
    o.append("namespace DetPrimality.Barrier\n")
    o.append("def dual2Chain : List (List (ℕ × ℕ) × DualSt) :=\n  [" + ",\n   ".join("(dual2Prog%d, dual2St%d)" % (k, k) for k in range(len(chunks))) + "]\n")
    o.append("theorem dual2Data_chain : DualChainOK dual2Par dual2VA dual2Lv (dualInit dual2VA) dual2Chain :=")
    o.append("  " + " ".join("(And.intro dual2Data_run%d" % k for k in range(len(chunks))) + " True.intro" + ")"*len(chunks) + "\n")
    o.append("theorem dual2Data_end : (dualChainEnd (dualInit dual2VA) dual2Chain).Y = dual2Yf := by decide +kernel\n")
    o.append("end DetPrimality.Barrier")
    open(os.path.join(outdir, "dual2_RunAll.lean"), "w").write("\n".join(o) + "\n")
