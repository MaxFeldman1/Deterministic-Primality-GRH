"""beyond_miller.py -- side-step of the barrier for the APPLICATION (Miller-Rabin), not for quadratic chi.

Claim (elementary, proof in beyond.md section 7): for every odd composite n != 9 the strong liars
(non-witnesses of the Miller-Rabin test) lie in a subgroup H of (Z/n)^* of index >= 4.
So "all a < X are non-witnesses" is an index-h >= 4 hypothesis, and the LLS/CMQR framework gives
C(1/3)^{-2} in (0.6029, 0.6131) instead of C(1)^{-2} in (0.7596, 0.7615).
This script brute-forces the index of the subgroup GENERATED by the strong liars.
"""
from math import gcd
import sys

def strong_liars(n):
    d, s = n-1, 0
    while d % 2 == 0: d //= 2; s += 1
    out = []
    for a in range(1, n):
        if gcd(a, n) != 1: continue
        x = pow(a, d, n)
        ok = (x == 1 or x == n-1)
        for _ in range(s-1):
            if ok: break
            x = x*x % n
            ok = (x == n-1)
        if ok: out.append(a)
    return out

def generated(n, gens):
    H = {1}
    for g in gens:
        if g in H: continue
        new = set(H); cur = set(H)
        while True:
            cur = {h*g % n for h in cur}
            if cur <= new: break
            new |= cur
        H = new
    return H

def is_prime(m):
    if m < 2: return False
    i = 2
    while i*i <= m:
        if m % i == 0: return False
        i += 1
    return True

def phi(n):
    r, m, p = n, n, 2
    while p*p <= m:
        if m % p == 0:
            while m % p == 0: m //= p
            r -= r//p
        p += 1
    if m > 1: r -= r//m
    return r

if __name__ == "__main__":
    N = int(sys.argv[1]) if len(sys.argv) > 1 else 6000
    hist, bad = {}, []
    extra = [8911, 10585, 15841, 29341, 41041, 46657, 52633, 62745, 63973, 75361]   # Carmichael numbers
    for n in list(range(9, N, 2)) + extra:
        if is_prime(n): continue
        L = strong_liars(n); H = generated(n, L)
        idx = phi(n)//len(H)
        hist[idx] = hist.get(idx, 0) + 1
        if idx < 4: bad.append((n, idx))
    print("odd composite n < %d (+%d Carmichael numbers): index of <strong liars> in (Z/n)^*" % (N, len(extra)))
    print("  indices < 4:", bad)
    print("  histogram of small indices:", {k: hist[k] for k in sorted(hist) if k <= 12})
    print("  examples with index exactly 4:", [n for n in range(9, min(N, 2000), 2) if not is_prime(n)
          and phi(n)//len(generated(n, strong_liars(n))) == 4][:15])
