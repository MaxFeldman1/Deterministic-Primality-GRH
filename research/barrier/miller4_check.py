"""miller4_check.py -- numerical sanity checks for miller4.md (evidence, not proof).

(K1) Lemma M11 (positivity): for odd composite n < NMAX, H = subgroup generated by the strong liars,
     S = all Dirichlet characters mod n trivial on H (|S| = h = [G:H]).  For every prime power m = p^r < 400
     (including p | n) the sum over chi in S of the PRIMITIVE character chi~(m) is a non-negative integer,
     equal to h when m is in H.  Characters are built from discrete logs modulo each prime power p_i^{e_i}.
(K2) Lemma M7 (prime side, index h, general lambda): direct evaluation of h T_<(X) - A_3(x) against
     (h-1)[D x^{3/2} - E1 x^{5/4} - E2 x] - rho_h(x), for h = 4 and lambda in {1/3, 1/4}, X prime (worst case).
(K3) the index of H and the shape of G/H (cyclic or Klein) for n < NMAX: min index, list of index-4 cases.
"""
import cmath, math, sys
from math import gcd, log, sqrt

NMAX = 1500

def factor(n):
    f = {}; d = 2
    while d*d <= n:
        while n % d == 0: f[d] = f.get(d, 0) + 1; n //= d
        d += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f

def is_strong_liar(a, n):
    d = n - 1; s = 0
    while d % 2 == 0: d //= 2; s += 1
    y = pow(a, d, n)
    if y == 1 or y == n - 1: return True
    for _ in range(s - 1):
        y = y*y % n
        if y == n - 1: return True
    return False

def prim_root(pe, p):
    phi = pe - pe//p
    fs = factor(phi)
    for g in range(2, pe):
        if g % p and all(pow(g, phi//q, pe) != 1 for q in fs): return g

def generated(gens, n):
    H = {1}; frontier = [1]
    while frontier:
        new = []
        for u in frontier:
            for g in gens:
                v = u*g % n
                if v not in H: H.add(v); new.append(v)
        frontier = new
    return H

def k1_k3():
    worst = (10**9, None); idx4 = []; nonneg_ok = True; ntests = 0; shapes = {}
    for n in range(9, NMAX, 2):
        f = factor(n)
        if len(f) == 1 and list(f.values())[0] == 1: continue      # prime
        units = [a for a in range(1, n) if gcd(a, n) == 1]
        liars = [a for a in units if is_strong_liar(a, n)]
        H = generated(liars, n)
        h = len(units)//len(H)
        if h < worst[0]: worst = (h, n)
        if h == 4: idx4.append(n)
        # discrete logs
        comps = []                                                  # (p, pe, phi, dlog table)
        for p, e in f.items():
            pe = p**e; phi = pe - pe//p; g = prim_root(pe, p)
            tab = {}; y = 1
            for i in range(phi): tab[y] = i; y = y*g % pe
            comps.append((p, pe, phi, tab))
        # characters = exponent vectors k with sum k_i dlog_i(a)/phi_i integral for all a in H (generators suffice)
        import itertools
        gens = liars
        chars = []
        for k in itertools.product(*[range(c[2]) for c in comps]):
            ok = True
            for a in gens:
                num = sum(ki*c[3][a % c[1]]*(math.lcm(*[cc[2] for cc in comps])//c[2]) for ki, c in zip(k, comps))
                if num % math.lcm(*[cc[2] for cc in comps]): ok = False; break
            if ok: chars.append(k)
        assert len(chars) == h, (n, len(chars), h)
        # shape of the quotient: exponent of the character group
        Lc = math.lcm(*[c[2] for c in comps])
        def order(k):
            o = 1
            for ki, c in zip(k, comps):
                if ki: o = math.lcm(o, c[2]//gcd(ki, c[2]))
            return o
        expo = max(order(k) for k in chars)
        shape = "cyclic" if expo == h else ("Klein" if h == 4 and expo == 2 else "non-cyclic, order > 4")
        shapes[shape] = shapes.get(shape, 0) + 1
        # primitive character values at prime powers m < 400
        if h > 64: continue                                          # keep the run short
        for p in [q for q in range(2, 400) if all(q % d for d in range(2, int(q**0.5) + 1))]:
            m = p
            while m < 400:
                tot = 0
                for k in chars:
                    val = 1
                    for ki, c in zip(k, comps):
                        if p == c[0]:
                            if ki: val = 0; break                    # chi~ ramified at p: chi~(p^r) = 0
                        else:
                            val *= cmath.exp(2j*cmath.pi*ki*c[3][m % c[1]]/c[2])
                    tot += val
                ntests += 1
                if abs(tot.imag) > 1e-7 or tot.real < -1e-7 or abs(tot.real - round(tot.real)) > 1e-7:
                    nonneg_ok = False; print("  FAIL n=%d m=%d sum=%s" % (n, m, tot))
                if m < n and gcd(m, n) == 1 and (m % n) in H and abs(tot.real - h) > 1e-7:
                    nonneg_ok = False; print("  FAIL(H) n=%d m=%d sum=%s" % (n, m, tot))
                m *= p
    print("(K3) odd composite n < %d: min index of <strong liars> = %d (n = %d); index 4 at %s%s" % (
        NMAX, worst[0], worst[1], idx4[:12], " ..." if len(idx4) > 12 else ""))
    print("     shape of G/<strong liars>: %s" % shapes)
    print("(K1) sum over chi in S of chi~(p^r) is a non-negative integer, = h on H: %s  (%d sums tested)" % (
        "ALL OK" if nonneg_ok else "FAILED", ntests))

def k2():
    N = 900000
    lamb = [0.0]*(N + 1); sieve = bytearray([1])*(N + 1)
    primes = []
    for p in range(2, N + 1):
        if sieve[p]:
            primes.append(p)
            for m in range(p*p, N + 1, p): sieve[m] = 0
            q = p
            while q <= N: lamb[q] = log(p); q *= p
    pp = [(m, lamb[m]) for m in range(2, N + 1) if lamb[m] > 0]
    Z2, Z3, Z4 = 0.047, 0.002375, 0.00012
    gam = [1.771, 0.148, 1.281, 0.0515]
    def r(j, y):
        ly = log(y)
        return sum(math.comb(j, i)*gam[j - i]*ly**i for i in range(j + 1)) + 0.64*math.factorial(j)
    for h, lam, name in ((4, 1/3, "1/3"), (4, 0.25, "1/4"), (2, 1/3, "1/3 (h=2 regression)")):
        l = log(1/lam)
        Pl = l**3 + 2*l*l + 8*l/3 + 16/9
        D = (h*(2/3)*lam**1.5*Pl - 32/27)/(h - 1)
        E1 = h/(h - 1)*2*l**3*sqrt(Z2)*lam**1.25
        E2 = (h*lam*(3*l*l*Z2 + 6*l*Z3 + 6*Z4) + 6*Z4)/(h - 1)
        worst = 1e9; worstX = None; cnt = 0
        Xs = [p for p in primes if 45 <= p <= N*lam - 1][::37]
        for X in Xs:
            x = X/lam
            T = 0.0; A3 = 0.0
            for m, lm in pp:
                if m >= x: break
                w = lm*sqrt(m)*log(x/m)**3
                A3 += w
                if m < X: T += w
            rho = h*(l**3*(gam[0] + 1) + 3*l*l*r(1, x) + 3*l*r(2, x) + r(3, x)) + r(3, x)
            lhs = h*T - A3
            rhs = (h - 1)*(D*x**1.5 - E1*x**1.25 - E2*x) - rho
            slack = (lhs - rhs)/((h - 1)*x**1.25)
            cnt += 1
            if slack < worst: worst, worstX = slack, X
        print("(K2) h = %d, lambda = %s: D = %.6f E1 = %.6f E2 = %.6f ; min over %d primes X in [45, %d] of "
              "(lhs - bound)/((h-1) x^{5/4}) = %+.4f at X = %d  -> %s" % (
                  h, name, D, E1, E2, cnt, Xs[-1], worst, worstX, "OK" if worst > 0 else "FAIL"))

if __name__ == "__main__":
    k1_k3()
    k2()
